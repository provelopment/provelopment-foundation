import { SPOKE_SELECTION_HEADER, isInternalSpokePath } from "@/config/spoke-selection";
import { EFS_REQUEST_PATH_HEADER } from "@/config/efs/request-path";
import {
  EFS_IMAGE_PATH_HEADER,
  EFS_OPEN_GRAPH_IMAGE_ROUTE,
  OPEN_GRAPH_IMAGE_SEGMENT,
} from "@/config/efs/image-path";

/**
 * THE REQUEST BOUNDARY: HOSTNAME DISPATCH (FOUNDATION-MULTISITE-M16/M17)
 * =====================================================================
 *
 * ONE decision order, and no global Spoke authority anywhere in it:
 *
 *     raw request host
 *         ↓ normalizeHostname + exact claim match   (`@/core/spoke`, via `@/config/spoke-routing`)
 *     ONE Spoke — or NOTHING
 *         ↓
 *     the PUBLIC pathname, unchanged, plus a PRIVATE upstream header naming that Spoke's runtime segment
 *         ↓
 *     the public catch-all App Router route resolves that context and calls the shared composition
 *
 * WHY THE PATH IS NOT REWRITTEN (M17 supersedes M16). The public path IS the page identity: the App Router
 * can only commit a client-side transition for a path it knows, and a rewritten flight response for a
 * DIFFERENT route tree cannot be applied to the requested public route. M16 measured both consequences — a
 * stuck soft navigation while a public page tree still existed and a full document reload once it did not —
 * so the Spoke now travels out of band on a private request header and the pathname is never touched.
 *
 * WHAT THIS FILE STILL DOES NOT DO: it reads no `siteConfig`, holds no Site or locale inventory, and completes
 * no locale. Site/locale completion is decided inside the selected Spoke — by the route boundary that already
 * holds that Spoke's fully resolved configuration — so the boundary never needs a configuration to answer a
 * routing question, and the browser-visible URL is never anything but the public one.
 *
 * THE TWO INSTALLATION SHAPES
 * ---------------------------
 *   multi   2+ declared Spokes: the host decides. An UNCLAIMED hostname answers NOTHING (404) — it is never
 *           redirected to another Spoke, never given "the first" Spoke and never given a default.
 *   single  exactly ONE declared Spoke: that Spoke answers every host, which is the accepted one-Spoke
 *           behaviour (development, preview and test hosts included) — stated as "the sole entry the build
 *           published", never as "the first".
 *
 * FAIL-CLOSED EXTRAS
 * ------------------
 *   · a DIRECT external request to the retired internal namespace (`/~spoke/**`) is refused: no page renders
 *     there, and a visitor never receives a surface that implies the namespace exists;
 *   · a Spoke's own asset namespace (`/spokes/<segment>/assets/**`) is HOST-BOUND: a host may fetch its own
 *     Spoke's artwork and never another's, even though both are generated in the same `public/` tree. The
 *     matcher below therefore also matches static (dotted) Spoke paths, while `/_next/**` and the shared
 *     `/assets/**` platform namespace stay untouched;
 *   · the RESERVED Open Graph image suffix (`…/opengraph-image`) is dispatched to the EFS image route on a
 *     host an EFS publication claims, and refused on a host it does not. That is the one path this file
 *     rewrites — because the App Router cannot express an image route under a catch-all — and the rewrite
 *     selects no publication: ownership is resolved by the same EFS chain every Page uses (`GEO-03` R04-C21).
 */
const SPOKE_ASSET_PREFIX = "/spokes/";

/** The reserved tree's spelling, folded — used ONLY to notice a variant and refuse it (R04-C24). */
const SPOKE_ASSET_PREFIX_FOLDED = SPOKE_ASSET_PREFIX.toLowerCase();

/**
 * `/spokes/<segment>/assets/<asset…>` — the ONE declared shape of a presentation-asset address.
 *
 * The `assets` segment is part of that address, so `ASSETS` is a DIFFERENT address rather than another way of
 * writing this one. A case-insensitive filesystem would happily resolve it, which is exactly why the grammar is
 * checked here instead of being left to the filesystem (`R04-C24`): a request must not reach generated bytes by
 * spelling the reserved tree differently.
 */
function isDeclaredAssetPath(pathname: string): boolean {
  const parts = pathname.split("/").filter(Boolean);
  return (
    parts.length >= 4 && parts[0] === "spokes" && parts[2] === "assets" && parts[3] !== ""
  );
}

/** Nothing answers this request: no Spoke, never another Spoke's content. */
function refuse(): NextResponse {
  return new NextResponse("Not Found", {
    status: 404,
    headers: { "content-type": "text/plain; charset=utf-8", "cache-control": "no-store" },
  });
}

/**
 * The request headers a caller may hand upstream, with the boundary's PRIVATE image-path marker removed
 * (`R04-C21-R02`).
 *
 * The marker is the ONE thing the internal image route trusts, so only the rewrite below may produce it: it is
 * deleted on the way in and re-set on the way out by that single branch. Every other way through this file —
 * an asset pass-through, a Spoke selection, an unclaimed host — must therefore strip whatever the client sent,
 * otherwise a direct request to the internal path could supply its own "original public path" and skip the
 * authorization the rewrite represents. A header the client controls is not an authorization.
 */
function passThroughHeaders(source: Headers): Headers {
  const headers = new Headers(source);
  headers.delete(EFS_IMAGE_PATH_HEADER);
  return headers;
}

/**
 * The runtime segment named by a Spoke asset path, or `null` if the path does not name exactly one.
 *
 * A namespace name is a SINGLE path segment, so this refuses anything that could address a different
 * namespace by construction: an empty segment, `.`/`..` (including the `%2e%2e` spelling, which decodes to
 * `..`), an encoded separator that would widen the segment, and embedded NUL. The proxy authorizes a
 * namespace; it must never authorize a PATH through one.
 */
function assetSegment(pathname: string): string | null {
  const raw = pathname.split("/").filter(Boolean)[1] ?? "";
  let decoded: string;
  try {
    decoded = decodeURIComponent(raw);
  } catch {
    // A malformed escape is not a namespace name.
    return null;
  }
  if (decoded === "" || decoded === "." || decoded === "..") return null;
  if (decoded.includes("/") || decoded.includes("\\") || decoded.includes("\u0000")) return null;
  return decoded;
}

/**
 * Continue WITHOUT the boundary's private headers.
 *
 * `SPOKE_SELECTION_HEADER` and `EFS_REQUEST_PATH_HEADER` are the boundary's own channel upstream. A path the
 * boundary does not resolve (a static asset namespace) must not carry a client-supplied value under those
 * names, so all three are DELETED rather than forwarded: a request cannot forge the Spoke, the binding or the
 * reserved image path that a later surface would read.
 */
function passThrough(request: NextRequest): NextResponse {
  const headers = passThroughHeaders(request.headers);
  headers.delete(SPOKE_SELECTION_HEADER);
  headers.delete(EFS_REQUEST_PATH_HEADER);
  return NextResponse.next({ request: { headers } });
}

/** The Spoke answering the CURRENT host, or `null` (dispatch: exact claims; single: the sole entry). */
function selectedEntry(
  routing: ReturnType<typeof hostRoutingForBuild>,
  host: string | null,
): SpokeHostRoutingEntry | null {
  // DISPATCH — the host decides. `identified` is dispatch too, deliberately (§6): an Installation authored
  // with identified Spoke Hubs never takes the permissive one-Spoke path below, even when it declares one
  // Hub and one Spoke, so an unknown host is refused there rather than answered by that Spoke.
  if (routing.mode !== "single") {
    const selection = spokeSelectionForHost(routing, host);
    if (selection === null) return null;
    // THE SELECTION'S OWN ENTRY, not a search by local id: where Spoke Hubs are identified, two Hubs may
    // each declare that id, and the entry is what carries the composite segment this request must resolve
    // (FOUNDATION-ID-M3-P2). A selection with no entry answers nothing rather than another Spoke's content.
    return routingEntryForSelection(routing, selection);
  }

  // ONE-Spoke compatibility: a LEGACY/FLAT build published exactly one entry, so there is nothing to choose.
  return routing.spokes.length === 1 ? routing.spokes[0] : null;
}

/**
 * Hand the request on with the selected Spoke declared on the PRIVATE upstream header — the pathname is
 * passed through exactly as the visitor requested it (that is the whole point: it stays the page identity).
 *
 * §6 — SPOOF-PROOF: the header is SET, never merely forwarded. Whatever a client sent under that name is
 * discarded and replaced by the boundary's own decision, so a request cannot choose its own Spoke. The
 * header is written into the upstream REQUEST only; it is never added to a response.
 */
function continueWithSelectedSpoke(request: NextRequest, entry: SpokeHostRoutingEntry): NextResponse {
  const headers = passThroughHeaders(request.headers);
  headers.set(SPOKE_SELECTION_HEADER, entry.runtimeSegment);
  // The public pathname is preserved, but the edge boundary is its authority. The Server Action
  // reads this private upstream header to resolve the exact EFS publication binding; any value a
  // client sent under the same name is discarded here.
  headers.set(EFS_REQUEST_PATH_HEADER, request.nextUrl.pathname);
  return NextResponse.next({ request: { headers } });
}

/**
 * A Spoke's own presentation artwork is served ONLY to a caller authorized to see THAT namespace.
 *
 * `declared` is not `published`. A Spoke declared in `spokes.json` has a namespace in `public/spokes/**`, but
 * that alone must not expose it: the authorization question is *does an explicit EFS publication on THIS host
 * name this Spoke?*, and only the build can answer it (the boundary has no filesystem). `@/config/spoke-routing`
 * carries the build's projection of the manifest's bindings; this function consumes it and decides nothing on
 * its own, so the proxy is not a second publication authority.
 *
 *   EFS PRESENT — this Installation's rights come from its publication bindings. Only Spokes those bindings
 *   name on THIS host may serve their namespace. An empty answer means "EFS controls this deployment and
 *   publishes nothing here", which is REFUSED: neither a declared Spoke nor an informational `site.url` may
 *   stand in for a publication, and an unreadable projection refuses everything.
 *
 *   EFS ABSENT — no EFS runtime is configured at all, so the released host-only rule applies unchanged: an
 *   exclusive host serves only its own selected Spoke, a shared host names no owner, an unclaimed host names
 *   nobody.
 */
function spokeAsset(request: NextRequest): NextResponse {
  const routing = hostRoutingForBuild();
  const host = request.headers.get("host");
  const { pathname } = request.nextUrl;
  // THE ADDRESS ITSELF IS AUTHORIZED, NOT JUST THE NAMESPACE (`R04-C24`). A case variant of the reserved prefix or
  // of the `assets` segment is a different address, and it must be REFUSED here rather than passed through and
  // resolved by a case-insensitive filesystem — otherwise generated bytes of an unpublished or other-Host Spoke
  // are reachable by spelling the tree differently. Nothing legitimate is lost: the declared spelling still serves.
  if (!pathname.startsWith(SPOKE_ASSET_PREFIX) || !isDeclaredAssetPath(pathname)) return refuse();
  const segment = assetSegment(pathname);
  // A namespace name is ONE path segment. Anything that could climb out of it is not a Spoke.
  if (segment === null) return refuse();

  const authority = presentationAssetAuthority(routing, host);
  if (authority.kind === "efs") {
    return authority.segments.has(segment) ? passThrough(request) : refuse();
  }

  const entry = isSharedHostInRouting(routing, host) ? null : selectedEntry(routing, host);
  if (entry === null || entry.runtimeSegment !== segment) return refuse();
  return passThrough(request);
}

/**
 * `/…/<locale>/opengraph-image` — the reserved image suffix, and never a Page path that merely ends in it.
 *
 * Stated as a SEGMENT comparison on purpose: this file must never decide anything from a hostname or a
 * substring of one (`multihost-runtime-guard`), and a path shape is a list of segments, not a string tail.
 */
function isReservedImagePath(pathname: string): boolean {
  const segments = pathname.split("/").filter((segment) => segment.length > 0);
  // A locale segment must precede the reserved suffix: `/opengraph-image` on its own names no owner.
  return segments.length >= 2 && segments[segments.length - 1] === OPEN_GRAPH_IMAGE_SEGMENT;
}

/**
 * THE RESERVED OPEN GRAPH IMAGE ENDPOINT (GEO-03 R04-C21)
 * ======================================================
 *
 * WHY THE BOUNDARY TOUCHES THIS ONE PATH. Next.js requires a catch-all segment to be the last segment that
 * modifies the path, so an image route cannot sit under `[[...segments]]`; the EFS tree therefore cannot serve
 * `/<locale>/opengraph-image` from the file tree at all. This is the narrowest possible answer: the reserved
 * suffix is rewritten to ONE internal route, and the ORIGINAL public path travels on a private header.
 *
 * WHAT IT STILL DECIDES: nothing. It selects no publication, reads no manifest, holds no Site or locale
 * inventory, and does not choose an image. It only proves the host is one an EFS publication claims — using
 * the same build-time projection the asset rule already uses — so the endpoint cannot be reached on a host
 * whose ownership is unknown. Every ownership question is then answered inside the image route by the same
 * EFS chain a Page uses, and an unclaimed host is REFUSED here rather than rewritten into a diagnostic.
 *
 * A rewritten path is a resource fetch, not a page navigation: no client-side transition is involved (the
 * M17 reason the public PATH of a page is never rewritten does not apply). The browser's address bar keeps
 * the public URL, which is what `og:image` must advertise.
 */
function imageEndpoint(request: NextRequest): NextResponse {
  const authority = presentationAssetAuthority(hostRoutingForBuild(), request.headers.get("host"));
  // NO EFS publication claims this host: this boundary owns nothing here and the path is LEFT UNTOUCHED.
  // A deployment without EFS keeps its released image route (the path is simply not ours), and on a
  // deployment WITH EFS an unclaimed host is answered by the EFS page boundary's own refusal — never by a
  // rewrite into an endpoint that could only guess an owner.
  if (authority.kind !== "efs" || authority.segments.size === 0) {
    return NextResponse.next({ request: { headers: passThroughHeaders(request.headers) } });
  }

  const forwarded = passThroughHeaders(request.headers);
  // The boundary DECLARES the public path; the delete above guarantees no client value can stand in for it.
  forwarded.set(EFS_IMAGE_PATH_HEADER, request.nextUrl.pathname);
  const url = request.nextUrl.clone();
  url.pathname = EFS_OPEN_GRAPH_IMAGE_ROUTE;
  return NextResponse.rewrite(url, { request: { headers: forwarded } });
}

export function proxy(request: NextRequest) {
  const { pathname } = request.nextUrl;

  // 1 — the retired internal namespace is not a page: nothing renders there.
  if (isInternalSpokePath(pathname)) return refuse();

  // 2 — a Spoke's own asset namespace is host-bound (static paths included — see the matcher). The reserved tree is
  // detected CASE-INSENSITIVELY so that a variant cannot slip past this boundary onto the filesystem, where a
  // case-insensitive filesystem would serve generated bytes this boundary never authorized; `spokeAsset` then
  // refuses every spelling except the one declared address (R04-C24).
  if (pathname.toLowerCase().startsWith(SPOKE_ASSET_PREFIX_FOLDED)) return spokeAsset(request);

  // 3 — the INTERNAL image route is not a public address (`R04-C21-R02`). Only the rewrite in step 4 may reach
  // it, and a rewrite does not re-enter this function. A caller asking for it directly is answered here, with
  // the same 404 as anything else that has no public identity — whatever headers it brought.
  if (pathname === EFS_OPEN_GRAPH_IMAGE_ROUTE) return refuse();

  // 4 — the reserved Open Graph image suffix is dispatched to the EFS image route (GEO-03 R04-C21).
  if (isReservedImagePath(pathname)) return imageEndpoint(request);

  // 5 — which Spoke answers this host: an exact claim, or no selection at all. An unclaimed
  // host is still handed to the App Router: EFS may own it, and otherwise the request context
  // refuses it with the same 404. No second runtime is selected here.
  const routing = hostRoutingForBuild();
  const entry = selectedEntry(routing, request.headers.get("host"));
  if (entry === null) {
    const forwarded = passThroughHeaders(request.headers);
    forwarded.delete(SPOKE_SELECTION_HEADER);
    forwarded.set(EFS_REQUEST_PATH_HEADER, pathname);
    return NextResponse.next({ request: { headers: forwarded } });
  }

  // 6 — the PUBLIC request continues unchanged, carrying the boundary's selection privately upstream.
  return continueWithSelectedSpoke(request, entry);
}

export const config = {
  /**
   * Every public path passes through this boundary EXCEPT `/_next/**`. The former `.*\..*` exclusion kept every
   * dotted path (that is, every static file) out of it, which also kept out the ONE static tree the boundary must
   * guard: a Spoke's asset namespace. `R04-C24` adds that such a request is matched here whatever the SPELLING of
   * the reserved prefix, because a case-insensitive filesystem would otherwise resolve `/SPOKES/<segment>/…` to
   * generated bytes this boundary never authorized. The boundary itself then refuses every spelling except the
   * declared one, and passes everything else through untouched, so `/_next/**` and the shared `/assets/**`
   * platform namespace behave exactly as before.
   */
  matcher: [
    "/((?!_next).*)",
    "/spokes/:path*",
  ],
};
